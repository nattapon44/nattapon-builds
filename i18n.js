export function initLanguage(onChange) {
  const bindings = [];
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement.closest('script, style, #nowViewing')) continue;
    const source = node.nodeValue.trim();
    if (Object.hasOwn(thai, source)) {
      const original = node.nodeValue;
      bindings.push(lang => { node.nodeValue = lang === 'th' ? original.replace(source, thai[source]) : original; });
    }
  }
  document.body.querySelectorAll('[aria-label], [alt], [data-nav]').forEach(element => {
    for (const attribute of ['aria-label', 'alt', 'data-nav']) {
      const source = element.getAttribute(attribute);
      if (Object.hasOwn(thai, source)) bindings.push(lang => element.setAttribute(attribute, lang === 'th' ? thai[source] : source));
    }
  });
  const buttons = [...document.querySelectorAll('[data-language]')];
  function apply(lang, persist = false) {
    const y = window.scrollY;
    const dialog = document.querySelector('#supportDialog');
    const dialogScroll = dialog?.scrollTop;
    document.documentElement.lang = lang;
    bindings.forEach(update => update(lang));
    buttons.forEach(button => button.setAttribute('aria-pressed', String(button.dataset.language === lang)));
    // The sample product heading is intentionally Thai in both portfolio languages.
    onChange();
    if (!dialog?.open) window.scrollTo({ top: y, behavior: 'instant' });
    if (dialog) dialog.scrollTop = dialogScroll;
    if (persist) { try { localStorage.setItem('nattapon-language', lang); } catch { /* Storage can be unavailable. */ } }
  }
  buttons.forEach(button => button.addEventListener('click', () => apply(button.dataset.language, true)));
  let saved;
  try { saved = localStorage.getItem('nattapon-language'); } catch { /* Default to English. */ }
  apply(saved === 'th' ? 'th' : 'en');
}
